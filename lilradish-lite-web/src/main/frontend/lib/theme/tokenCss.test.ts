import { describe, expect, it } from "vitest";
import { checkTokenCss, generateTokenCss } from "./tokenCss";

describe("the build-time token stylesheet", () => {
  it("uses rem for type sizes and leading while keeping other pixel tokens", () => {
    expect(
      generateTokenCss(
        'export const TOKENS = {shape: {controlRadius: "8px"}, type: {roles: {body: {fontSize: "14px", lineHeight: "22px", fontWeight: 400}}}} as const;',
      ),
    ).toBe(
      "/* Generated from tokens.ts. Checked byte for byte at build time. */\n/* prettier-ignore */\n:root {\n  --lr-shape-control-radius: 8px;\n  --lr-type-roles-body-font-size: 0.875rem;\n  --lr-type-roles-body-line-height: 1.375rem;\n  --lr-type-roles-body-font-weight: 400;\n}\n",
    );
  });
  it("leaves a type role's pixel values other than size and leading in pixels", () => {
    expect(
      generateTokenCss(
        'export const TOKENS = {type: {roles: {tag: {fontSize: "12px", letterSpacing: "1px"}}}} as const;',
      ),
    ).toBe(
      "/* Generated from tokens.ts. Checked byte for byte at build time. */\n/* prettier-ignore */\n:root {\n  --lr-type-roles-tag-font-size: 0.75rem;\n  --lr-type-roles-tag-letter-spacing: 1px;\n}\n",
    );
  });
  it("emits the exact CSS names and values without executing the source", () => {
    expect(
      generateTokenCss(
        'export const TOKENS = {surface: {card: "#ffffff"}, type: {roles: {body: {fontWeight: 400}}}} as const;',
      ),
    ).toBe(
      "/* Generated from tokens.ts. Checked byte for byte at build time. */\n/* prettier-ignore */\n:root {\n  --lr-surface-card: #ffffff;\n  --lr-type-roles-body-font-weight: 400;\n}\n",
    );
  });

  it.each([
    "export const TOKENS = {} as const;",
    "export const TOKENS = {colour: readColour()} as const;",
    "export const TOKENS = {...other} as const;",
    'export const TOKENS = {[name]: "red"} as const;',
    'export const TOKENS = {ground: "red; color: blue"} as const;',
    'export const TOKENS = {rowHover: "red", "row-hover": "blue"} as const;',
    'export const TOKENS = {ground: "red"};',
  ])("rejects a nonstatic or invalid source: %s", (source) => {
    expect(() => generateTokenCss(source)).toThrow();
  });

  it("rejects both a changed source and changed generated bytes", () => {
    const source = 'export const TOKENS = {ground: "#ffffff"} as const;';
    const css = generateTokenCss(source);
    expect(() => checkTokenCss(source, css)).not.toThrow();
    expect(() =>
      checkTokenCss(source.replace("ffffff", "f4f4f2"), css),
    ).toThrow("differs");
    expect(() => checkTokenCss(source, css + "\n")).toThrow("differs");
  });
});
