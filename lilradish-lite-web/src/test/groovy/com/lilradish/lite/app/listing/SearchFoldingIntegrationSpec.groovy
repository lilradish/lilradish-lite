package com.lilradish.lite.app.listing

import com.lilradish.lite.testsupport.TestPostgres
import com.lilradish.lite.testutil.Baseline
import java.sql.Connection
import javax.sql.DataSource
import org.springframework.jdbc.core.simple.JdbcClient
import org.springframework.jdbc.datasource.SingleConnectionDataSource
import spock.lang.AutoCleanup
import spock.lang.Shared
import spock.lang.Specification
import tools.jackson.databind.json.JsonMapper

/**
 * The one fold, held level on both sides it is applied to. Held text is folded once, when its row is
 * written, into a column the store generates; what a reader typed is folded when a search runs. Two
 * definitions of the fold would drift apart without any search failing loudly — names would simply
 * stop being found — so both sides are asked here of what the store itself holds.
 *
 * <p>The stored folds are discovered from the catalogue rather than listed, so a fold added to another
 * table is judged by the same rule the moment it exists. Rows a feature writes are rolled back.
 */
class SearchFoldingIntegrationSpec extends Specification {

    static final String COMBINING_ACUTE = Character.toString(0x0301)

    @Shared
    @AutoCleanup
    TestPostgres server = TestPostgres.worker()

    @Shared
    DataSource database

    def setupSpec() {
        database = Baseline.appliedTo(server, "postgres")
    }

    /**
     * Stored and virtual alike, because PostgreSQL 18 makes a column virtual unless it says STORED, and a
     * virtual one may call no user function: a fold there could only be a second copy of search_fold.
     */
    def "a generated column is a stored fold exactly where its name says so, by the function a search folds what was typed with"() {
        when:
        def session = JdbcClient.create(database)
        // DB-SPECIFIC: PostgreSQL :: casts to regnamespace; pg_attribute/pg_class/pg_attrdef; pg_get_expr().
        def generated = session.sql("""
                select table_of.relname || '.' || folded.attname as stored,
                       pg_get_expr(generation.adbin, generation.adrelid) as expression
                  from pg_attribute folded
                  join pg_class table_of on table_of.oid = folded.attrelid
                  join pg_attrdef generation
                    on generation.adrelid = folded.attrelid and generation.adnum = folded.attnum
                 where table_of.relnamespace = 'app'::regnamespace and folded.attgenerated <> ''
                """).query { row, number -> [row.getString("stored"), row.getString("expression")] }.list()
                .collectEntries()
        // DB-SPECIFIC: PostgreSQL :: casts to regnamespace; pg_attribute/pg_class.
        def notStored = session.sql("""
                select table_of.relname || '.' || folded.attname
                  from pg_attribute folded
                  join pg_class table_of on table_of.oid = folded.attrelid
                 where table_of.relnamespace = 'app'::regnamespace and table_of.relkind in ('r', 'p')
                   and folded.attnum > 0 and not folded.attisdropped
                   and folded.attname like '%\\_folded' and folded.attgenerated <> 's'
                """).query(String).list()
        def folds = generated.findAll { it.key.endsWith("_folded") }
        def others = generated.findAll { !it.key.endsWith("_folded") }

        then:
        folds.every { column, expression -> expression == "search_fold(${column.split("\\.", 2)[1] - ~/_folded$/})" }

        and: "every column named as a fold is stored, so none is written by hand or computed as it is read"
        notStored.isEmpty()

        and: "no column named otherwise folds anything"
        others.values().every { !it.contains("search_fold(") }

        and: "judged over folds and over other generated columns that both exist"
        !folds.isEmpty()
        !others.isEmpty()

        and: "the function every fold is generated by is the one a search applies to what was typed"
        SearchFolding.holds("held", ":typed").contains("search_fold(:typed)")
    }

    /**
     * Written one way and typed another — decomposed or composed, in either case, a letter folding to
     * two — the text typed whole or in part finds the name stored.
     */
    def "a name is found by what was typed however either side spelt its accents or cased its letters"() {
        expect:
        finds(stored, typed)

        where:
        stored                                   | typed
        "E" + COMBINING_ACUTE + "vren Mack"       | "évren mack"
        "Évren Mack"                              | "E" + COMBINING_ACUTE + "VREN"
        "Straße"                                  | "STRASSE"
        "greno nockal"                            | "GRENO NOCKAL"
        "山田　太郎"                                  | "田　太"
    }

    /**
     * The fold is canonical and not compatible, and Unicode's default rather than Turkish: an accent
     * typed bare, a full-width letter typed plain, and a dotted capital I typed as a plain i each find
     * nothing, which is accepted.
     */
    def "a name is not found by text only a looser fold would take for it"() {
        expect:
        !finds(stored, typed)

        where:
        stored       | typed
        "René"       | "Rene"
        "Ａri"        | "Ari"
        "İpek"       | "ipek"
        "Évren Mack" | "Evren"
    }

    def "literal LIKE agrees with the previous substring oracle across folded Unicode and metacharacters"() {
        given:
        def session = JdbcClient.create(database)
        def names = [null, '', '100% complete', 'under_score', 'bang!! !% !_ !', 'back\\slash',
                     'E' + COMBINING_ACUTE + 'vren', 'Évren', 'Straße', 'René', 'İpek', 'Ａri',
                     '山田　太郎', 'A😀B', 'a.b', 'two  spaces', 'plain']
        def typed = [null, '', '%', '_', '!', '!!', '!%', '!_', '\\', 'a', 'ab', '.',
                     'ÉV', 'E' + COMBINING_ACUTE, 'SS', 'Rene', 'i', 'Ａ', '田　太', '😀', '  ', 'missing']

        when:
        def observations = names.collectMany { held -> typed.collect { text ->
            // DB-SPECIFIC: PostgreSQL strpos and LIKE share the database's actual default text collation.
            session.sql("""
                    select strpos(search_fold(:held), search_fold(:typed)) > 0 as previous,
                           ${SearchFolding.holds('search_fold(:held)', ':typed')} as current
                    """).param('held', held).param('typed', text).query { row, number ->
                [held: held, typed: text, previous: row.getObject('previous'), current: row.getObject('current')]
            }.single()
        } }
        // DB-SPECIFIC: PostgreSQL catalogs expose collation OIDs, providers and determinism; regnamespace
        // resolves the schema, and current_setting() and version() read encoding and server version.
        def collations = session.sql("""
                select table_of.relname, attribute.attname, collated.collname,
                       collated.collprovider::text as provider, collated.collisdeterministic,
                       current_setting('server_encoding') as encoding, version() as server
                  from pg_catalog.pg_attribute attribute
                  join pg_catalog.pg_class table_of on table_of.oid = attribute.attrelid
                  join pg_catalog.pg_collation collated on collated.oid = attribute.attcollation
                 where table_of.relnamespace = 'app'::regnamespace
                   and attribute.attname like '%!_folded' escape '!'
                """).query().listOfRows()
        def output = System.getenv('SE2_QUERY_PLANS')
        if (output != null) {
            new File(output).mkdirs()
            new File(output, 'literal-oracle.json').text = JsonMapper.builder().build()
                    .writeValueAsString([observations: observations, collations: collations]) + '\n'
        }

        then:
        observations.size() == names.size() * typed.size()
        observations.every { it.previous == it.current }
        !collations.empty
        collations.every { it.encoding == 'UTF8' }
    }

    def "the deployed PostgreSQL records both predicates under a nondeterministic ICU collation"() {
        given:
        def session = JdbcClient.create(database)
        // DB-SPECIFIC: PostgreSQL ICU nondeterministic collation intentionally ignores case, accents and variable punctuation.
        session.sql("create collation s4_nondeterministic (provider = icu, locale = 'und-u-ka-shifted-ks-level1', deterministic = false)").update()
        def samples = [['a.b', 'ab'], ['René', 'Rene'], ['plain', 'PLAIN'], ['100% done', '%'],
                       ['under_score', '_'], ['a.b', 'a'], ['plain', ''], ['plain', null]]
        def outcomes = []

        when:
        samples.each { pair ->
            ['previous', 'current'].each { predicate ->
                // DB-SPECIFIC: PostgreSQL search_fold and strpos evaluate the previous predicate branch.
                def held = 'search_fold(:held) collate s4_nondeterministic'
                def expression = predicate == 'previous' ?
                        "strpos(${held}, search_fold(:typed)) > 0" : SearchFolding.holds(held, ':typed')
                try {
                    def value = session.sql("select ${expression}").param('held', pair[0]).param('typed', pair[1])
                            .query { row, number -> row.getObject(1) }.optional().orElse(null)
                    outcomes.add([held: pair[0], typed: pair[1], predicate: predicate, value: value])
                } catch (org.springframework.dao.DataAccessException failed) {
                    def cause = failed
                    while (cause.cause != null) cause = cause.cause
                    outcomes.add([held: pair[0], typed: pair[1], predicate: predicate,
                                  sqlstate: cause instanceof java.sql.SQLException ? cause.SQLState : null,
                                  error: cause.message])
                }
            }
        }
        def output = System.getenv('SE2_QUERY_PLANS')
        if (output != null) {
            new File(output).mkdirs()
            new File(output, 'nondeterministic-oracle.json').text = JsonMapper.builder().build()
                    .writeValueAsString(outcomes) + '\n'
        }

        then:
        outcomes.size() == samples.size() * 2
        outcomes*.predicate.toSet() == ['previous', 'current'] as Set
    }

    private boolean finds(String stored, String typed) {
        Connection connection = database.connection
        connection.autoCommit = false
        try {
            def session = JdbcClient.create(new SingleConnectionDataSource(connection, true))
            session.sql("insert into people (user_id, display_name) values ('000901', ?)").param(stored).update()
            session.sql("select count(*) from people where ${SearchFolding.holds('display_name_folded', ':typed')}")
                    .param("typed", typed).query(Long).single() == 1
        } finally {
            connection.rollback()
            connection.close()
        }
    }
}
